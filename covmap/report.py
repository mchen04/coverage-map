"""Coverage summary and comparison against scenario truth.

Skip semantics: a "skip" is an organ whose status is not ``reviewed`` (skipped or
partial). Per organ, with truth: TP = expected skip and measured skip, FP ("false skip")
= measured skip of an organ expected reviewed, FN = expected skip measured reviewed.
``exact_match`` requires every organ's measured status to equal its expected status.

Baseline comparison: the per-image model (covmap/baseline.py) "catches" a truth skip
when, crediting every voxel on a viewed image as reviewed, the organ would still not be
reviewed under the same thresholds.
"""

from __future__ import annotations

import json
from pathlib import Path

from covmap.baseline import implied_organ_coverage, viewed_from_ranges
from covmap.casedata import check_case, load_case
from covmap.errors import Refusal

SIMULATED_NOTE = ("Simulated reading: events are synthetic (source: simulated), generated by "
                  "covmap simulate; no human reader was involved.")
RESEARCH_NOTE = ("Research use only. Coverage measures what was displayed (slice, region, "
                 "window, dwell), not what was perceived or diagnosed.")


def _load(x) -> dict:
    if isinstance(x, dict):
        return x
    with open(x) as f:
        return json.load(f)


def _status(cov: float, params: dict) -> str:
    if cov >= params["reviewed_threshold"]:
        return "reviewed"
    return "skipped" if cov < params["skipped_threshold"] else "partial"


def compare(coverage: dict, truth: dict, case=None) -> dict:
    expected_map = truth["expected"]
    default = expected_map.get("*", "reviewed")
    organs = {o["key"]: o for o in coverage["organs"]}
    exp_cov = truth.get("expected_coverage", {})
    rows, counts = [], {"tp": 0, "fp": 0, "fn": 0, "tn": 0}
    for key, o in organs.items():
        exp = expected_map.get(key, default)
        act = o["status"]
        e_skip, a_skip = exp != "reviewed", act != "reviewed"
        outcome = ("tp" if a_skip else "fn") if e_skip else ("fp" if a_skip else "tn")
        counts[outcome] += 1
        rows.append({"key": key, "expected": exp, "actual": act, "coverage": o["coverage"],
                     "expected_coverage": exp_cov.get(key), "match": exp == act,
                     "outcome": outcome.upper()})
    missing = sorted(k for k in expected_map if k != "*" and k not in organs)
    out = {
        "scenario": truth.get("scenario"), "description": truth.get("description"),
        "source": truth.get("source"), **counts,
        "exact_match": all(r["match"] for r in rows) and not missing,
        "false_skips": [r["key"] for r in rows if r["outcome"] == "FP"],
        "missed_skips": [r["key"] for r in rows if r["outcome"] == "FN"],
        "mismatches": [r for r in rows if not r["match"]],
        "missing_organs": missing, "per_organ": rows,
    }
    base = coverage.get("baseline")
    if base is not None:
        b = {"flagged": not base["complete"], "complete": base["complete"],
             "unviewed_ranges": base["unviewed_ranges"],
             "expected_complete": truth.get("baseline_expected_complete")}
        if b["expected_complete"] is not None:
            b["matches_expected"] = base["complete"] == b["expected_complete"]
        if "baseline_expected_unviewed_ranges" in truth:
            b["ranges_match_expected"] = base["unviewed_ranges"] == truth["baseline_expected_unviewed_ranges"]
        skips = [r["key"] for r in rows if r["expected"] != "reviewed"]
        if case is not None:
            c = load_case(case)
            implied = implied_organ_coverage(c.organ_slice_counts,
                                             viewed_from_ranges(base["images"], base["unviewed_ranges"]))
            params = coverage["params"]
            by_key = {k: float(x) for k, x in zip(c.organ_keys, implied)}
            b["implied_coverage"] = {k: round(by_key[k], 6) for k in skips if k in by_key}
            b["catches"] = [k for k in skips if k in by_key and _status(by_key[k], params) != "reviewed"]
            b["cannot_catch"] = [k for k in skips if k not in b["catches"]]
            b["false_alarms"] = [r["key"] for r in rows if r["expected"] == "reviewed"
                                 and r["key"] in by_key and _status(by_key[r["key"]], params) != "reviewed"]
            measured = {r["key"] for r in rows if r["actual"] != "reviewed"}
            b["coverage_map_catches_all_baseline_catches"] = set(b["catches"]) <= measured
        out["baseline"] = b
    return out


def report(case_id, coverage_path, truth=None, out=None) -> dict:
    cov = _load(coverage_path)
    check_case(case_id, cov.get("case"), "coverage")
    sources = cov.get("events", {}).get("sources", {})
    simulated = bool(sources.get("simulated"))
    res = {
        "case": cov.get("case"), "session": cov.get("session"), "sources": sources,
        "simulated": simulated, "notes": ([SIMULATED_NOTE] if simulated else []) + [RESEARCH_NOTE],
        "params": cov.get("params"), "summary": cov.get("summary"), "baseline": cov.get("baseline"),
        "organs": [{"key": o["key"], "name": o.get("name"), "status": o["status"],
                    "coverage": o["coverage"], "reader": o.get("reader"), "flagged": o.get("flagged", False),
                    "top_unseen_reason": max(o["unseen"], key=o["unseen"].get) if o["status"] != "reviewed" else None}
                   for o in cov["organs"]],
    }
    if truth is not None:
        t = _load(truth)
        if t.get("case") not in (None, cov.get("case")):
            raise Refusal(f"truth is for case {t.get('case')!r}, coverage for {cov.get('case')!r}")
        res["truth"] = compare(cov, t, case=case_id)
        if t.get("source") == "simulated" and SIMULATED_NOTE not in res["notes"]:
            res["notes"].insert(0, SIMULATED_NOTE)
    if out:
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w") as f:
            json.dump(res, f, indent=1)
        res["out"] = str(out)
    return res
